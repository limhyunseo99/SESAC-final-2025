def calculate_quality_score(content: str) -> dict:
    """
    섹션 품질 점수 계산
    
    Args:
        content: 섹션 내용
        
    Returns:
        dict: {
            "score": int (0-100),
            "grade": str (A/B/C/D/F),
            "details": dict
        }
    """
    score = 100
    details = {}
    
    # 1. 출처 검증 (40점)
    source_result = validate_source_citations(content)
    if not source_result["valid"]:
        missing_ratio = source_result["missing_count"] / max(source_result["total_sentences"], 1)
        source_deduction = min(40, int(missing_ratio * 40))
        score -= source_deduction
        details["출처_누락"] = f"{source_result['missing_count']}개 문장"
    
    # 2. 분량 검증 (20점)
    char_count = len(content)
    if char_count < 400:
        score -= 20
        details["분량_부족"] = f"{char_count}자 (최소 400자)"
    elif char_count < 300:
        score -= 15
        details["분량_부족"] = f"{char_count}자"
    
    # 3. 일반론 표현 검증 (20점)
    general_phrases = ["유망하다", "경쟁이 심하다", "성장 가능성", "다양한", 
                       "증가할 것", "예상된다", "전망이다", "~하는 경향"]
    found_general = [p for p in general_phrases if p in content]
    if found_general:
        score -= min(20, len(found_general) * 5)
        details["일반론_표현"] = found_general
    
    # 4. 수치 데이터 포함 여부 (10점)
    import re
    numbers = re.findall(r'\d+[.,]?\d*[%억만달러원]', content)
    if len(numbers) < 2:
        score -= 10
        details["수치_부족"] = f"{len(numbers)}개"
    
    # 5. 표 포함 여부 (10점) - 시장 규모 등 데이터 섹션
    if '|' not in content and any(kw in content for kw in ['시장 규모', '수입액', '점유율']):
        score -= 10
        details["표_미사용"] = "데이터에 표 권장"
    
    # 등급 계산
    if score >= 90:
        grade = "A"
    elif score >= 80:
        grade = "B"
    elif score >= 70:
        grade = "C"
    elif score >= 60:
        grade = "D"
    else:
        grade = "F"
    
    return {
        "score": max(0, score),
        "grade": grade,
        "details": details
    }


