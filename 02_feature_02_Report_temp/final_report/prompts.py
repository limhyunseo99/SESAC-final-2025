def get_section_prompt(mode: str, context: str, existing_content: str = "", **kwargs) -> str:
    """
    섹션 생성 프롬프트 구성
    
    Args:
        mode: 'draft', 'verify', 'enhance_pdf', 'enhance_web'
        context: 참고 데이터
        existing_content: 기존 내용 (verify/enhance 모드에만 필요)
        **kwargs: country, item, section_key, country_code, hs_code 등
    """
    
    # 기존 내용 섹션 (verify/enhance만)
    existing_section = ""
    if mode in ["verify", "enhance_pdf", "enhance_web"] and existing_content:
        existing_section = EXISTING_CONTENT_TEMPLATE.format(existing_content=existing_content)
    
    # 모드별 지시사항
    mode_instruction = MODE_INSTRUCTIONS.get(mode, MODE_INSTRUCTIONS["draft"])
    
    # 최종 프롬프트
    return SECTION_GENERATION_PROMPT.format(
        mode=mode,
        mode_instructions=mode_instruction,
        existing_content_section=existing_section,
        context=context
    )